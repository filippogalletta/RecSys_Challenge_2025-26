if __name__ == "__main__":
    # 1) Load synthetic data and ground truth
    df, true_mech = load_synthetic_dataset()

    # Optional: define which columns we treat as "base features" for MAR logistic
    base_features = None  # they have no missing by construction

    # 2) Run detection
    pred_mech = detect_missing_mechanisms_dataset(
        df,
        alpha=0.05,
        auc_thresh=0.6,
        base_features=base_features,
    )

    # 3) Show per-column comparison
    comparison = compare_with_ground_truth(true_mech, pred_mech)
    print("\nPer-column true vs predicted mechanisms:")
    print(comparison.to_string(index=False))

    accuracy = comparison["correct"].mean()
    print(f"\nOverall accuracy: {accuracy:.3f}")

    # 4) Show confusion matrix
    print("\nConfusion matrix (true vs predicted):")
    print(confusion_matrix_mechanisms(true_mech, pred_mech))

    # 5) Detailed diagnostics: p-values and AUC per column
    print("\nDetailed diagnostics per column:")
    rows = []
    for col in df.columns:
        col_series = df[col]
        R = make_missing_indicator(col_series)

        # predictors: base features (x1,x2,x3) se ci sono, altrimenti tutte le altre
        if base_features is not None:
            predictors_cols = [c for c in base_features if c != col]
        else:
            predictors_cols = [c for c in df.columns if c != col]

        predictors = df[predictors_cols]

        min_p = chi_square_mcar_test(R, predictors, alpha=0.05)
        auc = logistic_mar_score(R, predictors)

        rows.append(
            {
                "column": col,
                "true": true_mech.get(col, "N/A"),
                "predicted": pred_mech[col],
                "min_pvalue": min_p,
                "auc": auc,
            }
        )

    diag_df = pd.DataFrame(rows)
    print(diag_df.to_string(index=False, float_format=lambda x: f"{x:.3f}"))