import json
from typing import Dict, List, Tuple

import numpy as np
import pandas as pd
from scipy.stats import chi2_contingency
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score


# -----------------------------------------------------------
# Utilities
# -----------------------------------------------------------

def load_synthetic_dataset(
    csv_path: str = "synthetic_missingness.csv",
    columns_json: str = "synthetic_missingness_columns.json",
    mech_json: str = "synthetic_missingness_mechanisms.json",
) -> Tuple[pd.DataFrame, Dict[str, str]]:
    """
    Load the synthetic dataset and metadata generated by
    generate_synthetic_missingness.py.

    Returns:
        df: pandas DataFrame with NaNs
        true_mechanisms: dict {col_name -> mechanism}
    """
    # Load column order
    with open(columns_json, "r") as f:
        col_meta = json.load(f)
    col_names = col_meta["columns"]

    # Load CSV into DataFrame
    df = pd.read_csv(csv_path, header=None)
    df.columns = col_names

    # Load ground-truth mechanisms
    with open(mech_json, "r") as f:
        true_mechanisms = json.load(f)

    return df, true_mechanisms


def make_missing_indicator(col: pd.Series) -> np.ndarray:
    """
    Given a pandas Series, return a 1D numpy array R where:
      R[i] = 1 if col[i] is NaN
             0 otherwise
    """
    return col.isna().astype(int).to_numpy()


def chi_square_mcar_test(
    R: np.ndarray,
    predictors: pd.DataFrame,
    n_bins: int = 4,
    alpha: float = 0.05,
) -> float:
    """
    Perform a simple MCAR check: for each predictor column,
    bin it into n_bins quantiles and run a chi-square test
    between the missingness indicator R and the binned predictor.

    Returns:
        min_pvalue: minimum p-value across predictors
    """
    pvalues: List[float] = []
    R_series = pd.Series(R)

    for col_name in predictors.columns:
        col = predictors[col_name]

        # Drop rows where predictor is NaN
        mask = ~col.isna()
        if mask.sum() == 0:
            continue

        R_valid = R_series[mask]
        x_valid = col[mask]

        # Bin the predictor into quantiles
        try:
            # qcut may fail if too few unique values
            binned = pd.qcut(x_valid, q=n_bins, duplicates="drop")
        except ValueError:
            # Fallback: no binning, skip this predictor
            continue

        contingency = pd.crosstab(R_valid, binned)

        # We need at least a 2 x k table
        if contingency.shape[0] < 2 or contingency.shape[1] < 2:
            continue

        try:
            chi2, p, dof, expected = chi2_contingency(contingency)
            pvalues.append(p)
        except Exception:
            # Any numerical issue, just skip this predictor
            continue

    if not pvalues:
        # If we couldn't compute any test, be conservative: return 0.0
        return 0.0

    return float(np.min(pvalues))


def logistic_mar_score(
    R: np.ndarray,
    predictors: pd.DataFrame,
    max_iter: int = 200,
) -> float:
    """
    Fit a logistic regression model R ~ predictors and compute the AUC.
    We drop rows with any missing in predictors.

    Returns:
        auc: ROC AUC score in [0, 1]; if not computable, returns 0.5
    """
    # Combine R and predictors into one DataFrame to drop NaNs jointly
    data = predictors.copy()
    data["R"] = R

    data = data.dropna()
    if data.shape[0] < 20:
        # Not enough data to fit a model
        return 0.5

    y = data["R"].to_numpy()
    X = data.drop(columns=["R"]).to_numpy()

    # If only one class in R, AUC is undefined
    if len(np.unique(y)) < 2:
        return 0.5

    try:
        model = LogisticRegression(
            solver="lbfgs",
            max_iter=max_iter,
        )
        model.fit(X, y)
        # Use predicted probabilities for class 1
        prob = model.predict_proba(X)[:, 1]
        auc = roc_auc_score(y, prob)
        return float(auc)
    except Exception:
        return 0.5


