# Main detection logic
# -----------------------------------------------------------

def detect_missing_mechanism_for_column(
    df: pd.DataFrame,
    col_name: str,
    alpha: float = 0.05,
    auc_thresh: float = 0.7,
    base_features: List[str] = None,
) -> str:
    """
    Classify the missingness mechanism for a single column:
    returns one of: "none", "MCAR", "MAR", "MNAR".
    """

    col = df[col_name]
    R = make_missing_indicator(col)

    # Case 1: no missing at all
    if R.sum() == 0:
        return "none"

    # Choose predictors:
    # if base_features is given, use those (and drop col_name if present).
    # otherwise, use all other columns except the target column itself.
    if base_features is not None:
        predictors_cols = [c for c in base_features if c != col_name]
    else:
        predictors_cols = [c for c in df.columns if c != col_name]

    predictors = df[predictors_cols]

    # 1) MCAR check via chi-square tests
    min_pvalue = chi_square_mcar_test(R, predictors, alpha=alpha)
    # If all tests show no dependence (min p > alpha) -> MCAR
    if min_pvalue > alpha:
        return "MCAR"

    # 2) MAR vs MNAR check via logistic regression on observed predictors
    auc = logistic_mar_score(R, predictors)

    if auc >= auc_thresh:
        return "MAR"

    # 3) Fallback: MNAR
    return "MNAR"


def detect_missing_mechanisms_dataset(
    df: pd.DataFrame,
    alpha: float = 0.05,
    auc_thresh: float = 0.7,
    base_features: List[str] = None,
) -> Dict[str, str]:
    """
    Run missingness mechanism detection for all columns in df.

    Returns:
        pred_mechanisms: dict {col_name -> predicted mechanism}
    """
    pred: Dict[str, str] = {}
    for col in df.columns:
        mech = detect_missing_mechanism_for_column(
            df,
            col,
            alpha=alpha,
            auc_thresh=auc_thresh,
            base_features=base_features,
        )
        pred[col] = mech
    return pred


def compare_with_ground_truth(
    true_mech: Dict[str, str],
    pred_mech: Dict[str, str],
) -> pd.DataFrame:
    """
    Build a small summary table comparing true vs predicted mechanisms.
    """
    rows = []
    for col in pred_mech.keys():
        rows.append(
            {
                "column": col,
                "true": true_mech.get(col, "N/A"),
                "predicted": pred_mech[col],
                "correct": true_mech.get(col, "N/A") == pred_mech[col],
            }
        )
    return pd.DataFrame(rows)


def confusion_matrix_mechanisms(
    true_mech: Dict[str, str],
    pred_mech: Dict[str, str],
) -> pd.DataFrame:
    """
    Build a confusion matrix (true vs predicted mechanisms).
    """
    data = {
        "true": [],
        "predicted": [],
    }
    for col, t in true_mech.items():
        if col not in pred_mech:
            continue
        data["true"].append(t)
        data["predicted"].append(pred_mech[col])
    df_res = pd.DataFrame(data)
    cm = pd.crosstab(df_res["true"], df_res["predicted"])
    return cm


